// Command witgen writes the core imports of a WIT interface for Go guests
// (GOOS=wasip1): one //go:wasmimport per function and resource drop, with
// its Canonical ABI core signature (package wit), and a table from import
// name to a call taking and returning core values as uint64. The guest
// package lowers and lifts with package wit around it, so guest and host
// share one implementation of the ABI.
//
//	go run ./internal/cmd/witgen --wit webgpu/wit/webgpu.wit --wit webgpu/wit/surface.wit \
//	  --interface webgpu --interface surface --interface surface-webgpu --package wasigpu --out wasigpu/imports_wasip1.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/spf13/cobra"

	"github.com/go-wasmcontainers/gpu/wit"
)

var osExit = os.Exit

func main() {
	if err := RootCmd().Execute(); err != nil {
		osExit(1)
	}
}

// RootCmd is the command, for tests.
func RootCmd() *cobra.Command {
	var srcs, ifaces []string
	var pkg, out string
	cmd := &cobra.Command{
		Use:          "witgen --wit FILE... --interface NAME... --package NAME --out FILE",
		Short:        "Write Go wasmimport declarations for WIT interfaces",
		SilenceUsage: true,
		Args:         cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			// Each file is a package; later files may use earlier ones.
			byName := map[string]*wit.Interface{}
			var deps []*wit.Interface
			for _, src := range srcs {
				b, err := os.ReadFile(src)
				if err != nil {
					return err
				}
				ifs, err := wit.ParseFiles(deps, string(b))
				if err != nil {
					return err
				}
				for n, i := range ifs {
					byName[n] = i
					deps = append(deps, i)
				}
			}
			var sel []*wit.Interface
			for _, n := range ifaces {
				i := byName[n]
				if i == nil {
					return fmt.Errorf("no interface %q", n)
				}
				sel = append(sel, i)
			}
			code, err := Generate(sel, pkg)
			if err != nil {
				return err
			}
			if err := os.WriteFile(out, code, 0o644); err != nil {
				return err
			}
			fmt.Fprintf(cmd.OutOrStdout(), "wrote %s\n", out)
			return nil
		},
	}
	f := cmd.Flags()
	f.StringArrayVar(&srcs, "wit", nil, "WIT file (a package); repeat, dependencies first")
	f.StringArrayVar(&ifaces, "interface", nil, "interface name; repeat")
	f.StringVar(&pkg, "package", "", "Go package of the output")
	f.StringVar(&out, "out", "", "output file")
	for _, n := range []string{"wit", "interface", "package", "out"} {
		_ = cmd.MarkFlagRequired(n)
	}
	return cmd
}

var goType = map[byte]string{wit.I32: "uint32", wit.I64: "uint64", wit.F32c: "float32", wit.F64c: "float64"}

// toCore converts a core value held as uint64 into the Go parameter type.
func toCore(c byte, v string) string {
	switch c {
	case wit.I32:
		return "uint32(" + v + ")"
	case wit.F32c:
		return "math.Float32frombits(uint32(" + v + "))"
	case wit.F64c:
		return "math.Float64frombits(" + v + ")"
	}
	return v
}

func fromCore(c byte, v string) string {
	switch c {
	case wit.I32:
		return "uint64(" + v + ")"
	case wit.F32c:
		return "uint64(math.Float32bits(" + v + "))"
	case wit.F64c:
		return "math.Float64bits(" + v + ")"
	}
	return v
}

// Generate returns the Go source. The calls table is keyed by
// "module name" (the ImportModule, a space, the import name).
func Generate(ifs []*wit.Interface, pkg string) ([]byte, error) {
	type imp struct {
		module, name   string
		params, result string
	}
	var imps []imp
	var mods []string
	for _, i := range ifs {
		mods = append(mods, i.ImportModule())
		for _, f := range i.Funcs {
			s := wit.Sig(f)
			imps = append(imps, imp{i.ImportModule(), f.ImportName(""), string(s.Params), string(s.Results)})
		}
		for _, r := range i.ResourceNames() {
			for _, f := range i.Resources[r].Funcs {
				s := wit.Sig(f)
				imps = append(imps, imp{i.ImportModule(), f.ImportName(r), string(s.Params), string(s.Results)})
			}
			imps = append(imps, imp{i.ImportModule(), "[resource-drop]" + r, "i", ""})
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/cmd/witgen from the WIT of %s; DO NOT EDIT.\n\n", strings.Join(mods, ", "))
	fmt.Fprintf(&b, "//go:build wasip1\n\npackage %s\n\nimport \"math\"\n\nvar _ = math.Float32bits\n\n", pkg)
	for n, im := range imps {
		var ps []string
		for j := 0; j < len(im.params); j++ {
			ps = append(ps, fmt.Sprintf("p%d %s", j, goType[im.params[j]]))
		}
		res := ""
		if im.result != "" {
			res = " " + goType[im.result[0]]
		}
		fmt.Fprintf(&b, "//go:wasmimport %s %s\n//go:noescape\nfunc imp%d(%s)%s\n\n", im.module, im.name, n, strings.Join(ps, ", "), res)
	}
	fmt.Fprintf(&b, "// calls maps \"module name\" to a call over core values.\nvar calls = map[string]func(a []uint64) uint64{\n")
	for n, im := range imps {
		var args []string
		for j := 0; j < len(im.params); j++ {
			args = append(args, toCore(im.params[j], fmt.Sprintf("a[%d]", j)))
		}
		call := fmt.Sprintf("imp%d(%s)", n, strings.Join(args, ", "))
		key := im.module + " " + im.name
		if im.result == "" {
			fmt.Fprintf(&b, "%q: func(a []uint64) uint64 { %s; return 0 },\n", key, call)
		} else {
			fmt.Fprintf(&b, "%q: func(a []uint64) uint64 { return %s },\n", key, fromCore(im.result[0], call))
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
