// Command witgen writes the core imports of a WIT interface for Go guests
// (GOOS=wasip1): one //go:wasmimport per function and resource drop, with
// its Canonical ABI core signature (package wit), and a table from import
// name to a call taking and returning core values as uint64. The guest
// package lowers and lifts with package wit around it, so guest and host
// share one implementation of the ABI.
//
//	go run ./internal/cmd/witgen --wit webgpu/wit/webgpu.wit --interface webgpu --package wasigpu --out wasigpu/imports_wasip1.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/spf13/cobra"

	"github.com/go-wasmcontainers/gpu/wit"
)

var osExit = os.Exit

func main() {
	if err := RootCmd().Execute(); err != nil {
		osExit(1)
	}
}

// RootCmd is the command, for tests.
func RootCmd() *cobra.Command {
	var src, iface, pkg, out string
	cmd := &cobra.Command{
		Use:          "witgen --wit FILE --interface NAME --package NAME --out FILE",
		Short:        "Write Go wasmimport declarations for a WIT interface",
		SilenceUsage: true,
		Args:         cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			b, err := os.ReadFile(src)
			if err != nil {
				return err
			}
			ifs, err := wit.Parse(string(b))
			if err != nil {
				return err
			}
			i := ifs[iface]
			if i == nil {
				return fmt.Errorf("no interface %q", iface)
			}
			code, err := Generate(i, pkg)
			if err != nil {
				return err
			}
			if err := os.WriteFile(out, code, 0o644); err != nil {
				return err
			}
			fmt.Fprintf(cmd.OutOrStdout(), "wrote %s\n", out)
			return nil
		},
	}
	f := cmd.Flags()
	f.StringVar(&src, "wit", "", "WIT file")
	f.StringVar(&iface, "interface", "", "interface name")
	f.StringVar(&pkg, "package", "", "Go package of the output")
	f.StringVar(&out, "out", "", "output file")
	for _, n := range []string{"wit", "interface", "package", "out"} {
		_ = cmd.MarkFlagRequired(n)
	}
	return cmd
}

var goType = map[byte]string{wit.I32: "uint32", wit.I64: "uint64", wit.F32c: "float32", wit.F64c: "float64"}

// toCore converts a core value held as uint64 into the Go parameter type.
func toCore(c byte, v string) string {
	switch c {
	case wit.I32:
		return "uint32(" + v + ")"
	case wit.F32c:
		return "math.Float32frombits(uint32(" + v + "))"
	case wit.F64c:
		return "math.Float64frombits(" + v + ")"
	}
	return v
}

func fromCore(c byte, v string) string {
	switch c {
	case wit.I32:
		return "uint64(" + v + ")"
	case wit.F32c:
		return "uint64(math.Float32bits(" + v + "))"
	case wit.F64c:
		return "math.Float64bits(" + v + ")"
	}
	return v
}

// Generate returns the Go source.
func Generate(i *wit.Interface, pkg string) ([]byte, error) {
	type imp struct {
		name           string
		params, result string
	}
	var imps []imp
	for _, f := range i.Funcs {
		s := wit.Sig(f)
		imps = append(imps, imp{f.ImportName(""), string(s.Params), string(s.Results)})
	}
	for _, r := range i.ResourceNames() {
		for _, f := range i.Resources[r].Funcs {
			s := wit.Sig(f)
			imps = append(imps, imp{f.ImportName(r), string(s.Params), string(s.Results)})
		}
		imps = append(imps, imp{"[resource-drop]" + r, "i", ""})
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/cmd/witgen from the WIT of %s; DO NOT EDIT.\n\n", i.ImportModule())
	fmt.Fprintf(&b, "//go:build wasip1\n\npackage %s\n\nimport \"math\"\n\nvar _ = math.Float32bits\n\n", pkg)
	for n, im := range imps {
		var ps []string
		for j := 0; j < len(im.params); j++ {
			ps = append(ps, fmt.Sprintf("p%d %s", j, goType[im.params[j]]))
		}
		res := ""
		if im.result != "" {
			res = " " + goType[im.result[0]]
		}
		fmt.Fprintf(&b, "//go:wasmimport %s %s\n//go:noescape\nfunc imp%d(%s)%s\n\n", i.ImportModule(), im.name, n, strings.Join(ps, ", "), res)
	}
	fmt.Fprintf(&b, "// calls maps an import name to a call over core values.\nvar calls = map[string]func(a []uint64) uint64{\n")
	for n, im := range imps {
		var args []string
		for j := 0; j < len(im.params); j++ {
			args = append(args, toCore(im.params[j], fmt.Sprintf("a[%d]", j)))
		}
		call := fmt.Sprintf("imp%d(%s)", n, strings.Join(args, ", "))
		if im.result == "" {
			fmt.Fprintf(&b, "%q: func(a []uint64) uint64 { %s; return 0 },\n", im.name, call)
		} else {
			fmt.Fprintf(&b, "%q: func(a []uint64) uint64 { return %s },\n", im.name, fromCore(im.result[0], call))
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
